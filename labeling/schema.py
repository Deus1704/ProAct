def stratum_counts(participant_id: str, path: str | None = None) -> dict[str, int]:
    """Population size per stratum, the denominator of the inclusion probability."""
    with get_db(path) as conn:
        rows = conn.execute(
            "SELECT stratum, COUNT(*) c FROM candidates WHERE participant_id=? GROUP BY stratum",
            (participant_id,),
        ).fetchall()
    return {r["stratum"]: r["c"] for r in rows}


def candidates_in_stratum(
    participant_id: str, stratum: str, path: str | None = None
) -> list[dict[str, Any]]:
    with get_db(path) as conn:
        rows = conn.execute(
            "SELECT * FROM candidates WHERE participant_id=? AND stratum=? ORDER BY candidate_id",
            (participant_id, stratum),
        ).fetchall()
    return [dict(r) for r in rows]


def labelled_rows(path: str | None = None) -> list[dict[str, Any]]:
    """Everything needed for weighted estimation, in one join."""
    with get_db(path) as conn:
        rows = conn.execute(
            """SELECT c.candidate_id, c.participant_id, c.domain, c.decided_at,
                      c.stratum, c.fired_prod, c.reason, c.confidence, c.threshold,
                      c.pattern_ref, c.context_json,
                      i.item_id, i.inclusion_prob, i.position, i.is_gold, i.gold_expected,
                      b.batch_id, b.kind,
                      r.welcome, r.wanted, r.did_act, r.latency_ms, r.answered_at
               FROM items i
               JOIN candidates c ON c.candidate_id = i.candidate_id
               JOIN batches    b ON b.batch_id     = i.batch_id
               LEFT JOIN responses r ON r.item_id  = i.item_id
               ORDER BY b.batch_id, i.position"""
        ).fetchall()
    return [dict(r) for r in rows]
